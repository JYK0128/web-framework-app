import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsString, Length } from 'class-validator';

import { EntityType } from '#/common/dto/entity-dto';
import { Verification } from '#/entities/auth/verification.entity';

export class Verify2FAChallengeRequestDto extends EntityType(Verification) {
  @ApiProperty({ description: 'The 6-digit 2FA code generated by the authenticator app', example: '123456' })
  @IsString()
  @IsNotEmpty()
  @Length(6, 6)
  code!: string;

  token!: string;
}
