import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsString, Length } from 'class-validator';

export class Verify2FAChallengeRequestDto {
  @ApiProperty({ description: 'The 6-digit 2FA code generated by the authenticator app', example: '123456' })
  @IsString()
  @IsNotEmpty()
  @Length(6, 6)
  code!: string;

  @ApiProperty({ description: 'Challenge verification token' })
  @IsString()
  @IsNotEmpty()
  token!: string;
}
